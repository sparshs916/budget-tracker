#!/bin/bash
# Cloud-session setup: Python deps, a local Postgres, and a demo .env so
# `pytest` and the dev server work out of the box.
set -euo pipefail

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

cd "$CLAUDE_PROJECT_DIR"

# --- Python ---
if [ ! -x .venv/bin/python ]; then
  python3 -m venv .venv
fi
.venv/bin/pip install -q --disable-pip-version-check -r requirements.txt pytest ruff

# --- Postgres (runs as the postgres user; root can't run it) ---
PG_BIN=$(ls -d /usr/lib/postgresql/*/bin | sort -V | tail -1)
PG_DATA=/var/lib/postgresql/budget-dev
if [ ! -f "$PG_DATA/PG_VERSION" ]; then
  mkdir -p "$PG_DATA"
  chown postgres:postgres "$PG_DATA"
  su postgres -c "$PG_BIN/initdb -D $PG_DATA -A trust -U postgres" >/dev/null
fi
if ! "$PG_BIN/pg_isready" -q -h /var/run/postgresql -p 5432; then
  su postgres -c "$PG_BIN/pg_ctl -D $PG_DATA -l $PG_DATA/server.log -o '-p 5432 -k /var/run/postgresql' -w start" >/dev/null
fi
for db in budget_dev budget_test; do
  psql -h /var/run/postgresql -U postgres -tAc "SELECT 1 FROM pg_database WHERE datname='$db'" | grep -q 1 \
    || psql -h /var/run/postgresql -U postgres -qc "CREATE DATABASE $db"
done

# --- Demo .env (never overwrites an existing one) ---
if [ ! -f .env ]; then
  .venv/bin/python - <<'PY'
import secrets
from cryptography.fernet import Fernet
from werkzeug.security import generate_password_hash
lines = {
    "DATABASE_URL": "postgresql://postgres@/budget_dev?host=/var/run/postgresql",
    "APP_PASSWORD_HASH": generate_password_hash("demo-password", method="scrypt"),
    "SECRET_KEY": secrets.token_urlsafe(48),
    "TOKEN_ENCRYPTION_KEY": Fernet.generate_key().decode(),
    "CRON_SECRET": secrets.token_urlsafe(32),
}
with open(".env", "w") as f:
    f.write("# Generated by .claude/hooks/session-start.sh for local demo use. Login password: demo-password\n")
    f.writelines(f"{k}='{v}'\n" for k, v in lines.items())
PY
fi

{
  echo "export PATH=\"$CLAUDE_PROJECT_DIR/.venv/bin:\$PATH\""
  echo "export TEST_DATABASE_URL='postgresql://postgres@/budget_test?host=/var/run/postgresql'"
} >> "$CLAUDE_ENV_FILE"
